export function useCaixaT() {
  const { lang } = useI18n();
  return (key: keyof typeof dictionaries.pt, vars?: Record<string, string | number>) =>
    dictionaries[lang][key].replace(/\{\{(\w+)\}\}/g, (_, k: string) => String(vars?.[k] ?? ''));
}